export function projectById(id: string): ProjectEntry {
    const entry = projectEntries.find((project) => project.id === id);

    if (!entry) {
        throw new Error(`Unknown project: ${id}`);
    }

    return entry;
}

export function featuredProjects(): ProjectEntry[] {
    return projectEntries.filter((project) => project.featured);
}
