import { boidsUrl, chaosEquationsUrl, githubProfileUrl, repos } from "../pages/constants";

export type ProjectLink = {
    label: string;
    href: string;
};

export type ProjectImage = {
    /** Public path to a thumbnail depicting the project's actual output. */
    src: string;
    /** Describes the image for screen readers and machine-readable copies. */
    alt: string;
};

/**
 * Dates are kept separate and optional because not every project has a known
 * creation date. A period is always the honest display value; an exact date is
 * only recorded when there is a source for it.
 */
export type ProjectDates = {
    /** When work began, if a source exists. */
    started?: string;
    /** When the reported measurements were taken, if a source exists. */
    measured?: string;
    /** When this write-up was published. */
    published?: string;
};

export type ProjectEntry = {
    id: string;
    number: string;
    title: string;
    /** Short label used beside the title, e.g. "Digital hardware". */
    category: string;
    description: string;
    /** The constraint or question the project addresses. */
    problem: string;
    /** The part of the work that is specifically mine. */
    contribution: string;
    period: string;
    /** Structured technology list used by the page, cards, and projects.json. */
    technologies: string[];
    dates?: ProjectDates;
    image: ProjectImage;
    /** Internal route for a project with its own page. */
    path?: string;
    /** Where the project title links, if it links at all. */
    titleHref?: string;
    links: ProjectLink[];
    keywords: string[];
    /** Set on the five projects shown in the homepage selected-work list. */
    featured?: boolean;
    metric?: string;
    metricLabel?: string;
};

